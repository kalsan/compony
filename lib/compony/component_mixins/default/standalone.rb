module Compony
  module ComponentMixins
    module Default
      # @api description
      # This contains all default component logic concerning standalone functionality. The module is included in every component.
      module Standalone
        extend ActiveSupport::Concern

        included do
          # Called in routes.rb
          # Returns the compiled standalone config for this component
          # If the components have an inheritance hierarchy, the configs are merged in the right order to perform proper overrides.
          attr_reader :standalone_configs
        end

        # Called by compony_controller when a request is issued.
        # This is the entrypoint where a request enters the Component world.
        # @param verb_config [Hash] The config generated by Compony::ComponentMixins::Default::Standalone::VerbDsl#to_conf
        # @param controller [ComponyController] The controller instance that calls this method.
        # @see ComponyController
        def on_standalone_access(verb_config, controller)
          # Register as root comp
          if parent_comp.nil?
            fail "#{inspect} is attempting to become root component, but #{root_comp.inspect} is already root." if Compony.root_comp.present?
            RequestStore.store[:compony_root_comp] = self
          end

          # Prepare the request context in which the innermost DSL calls will be executed
          request_context = RequestContext.new(self, controller)

          # A GET that assigns attributes (e.g. Edit or New prefilled from params) may read and render, but never persist: assigning
          # `*_ids` or a `has_one` to a persisted record writes to the database immediately, and so would any hook doing an action on GET.
          # Run such a request in a transaction that is always rolled back. Non-database side effects (external calls, mails sent
          # right away, jobs in a separate queue database) are not undone.
          # A write that must survive (e.g. a statistics counter) goes into `outside_rollback { ... }`, which runs after the rollback.
          if verb_config.assign_attributes_block && (controller.request.get? || controller.request.head?) && defined?(ActiveRecord::Base)
            RequestStore.store[:compony_outside_rollback_blocks] = []
            begin
              # requires_new makes this a savepoint when a transaction is already open (e.g. transactional tests), so the rollback is real.
              ActiveRecord::Base.transaction(requires_new: true) do
                dispatch_standalone_access(verb_config, controller, request_context)
                fail ActiveRecord::Rollback
              end
              deferred_blocks = RequestStore.store[:compony_outside_rollback_blocks]
            ensure
              RequestStore.store[:compony_outside_rollback_blocks] = nil
            end
            deferred_blocks.each(&:call)
          else
            dispatch_standalone_access(verb_config, controller, request_context)
          end
        end

        # Runs the block so that its database writes persist even in a GET that assigns attributes, whose writes are otherwise rolled
        # back (see {#on_standalone_access}). In such a request, the block is deferred until after the rollback; in any other context
        # it runs right away. Use it sparingly, for writes that are intended on GET, e.g. marking a link as opened or counting views.
        # When deferred, the block runs after the response was rendered: rows created during the request no longer exist then, and
        # in-memory changes made during the request (e.g. assigned params) are not in the database. Write with explicit values or SQL.
        # @yield The write to persist.
        # @return [void]
        # @api public
        def outside_rollback(&block)
          deferred_blocks = RequestStore.store[:compony_outside_rollback_blocks]
          if deferred_blocks
            deferred_blocks << block
          else
            block.call
          end
        end

        # Runs the lifecycle of a standalone request. Called by {#on_standalone_access}, do not call directly.
        # Lifecycle is (see also "doc/Resourceful Lifecycle.pdf"):
        #   - load data (optional, speficied ResourcefulVerbDsl, by convention, should default to the implementation in Resourceful)
        #     - after_load_data (optional, specified in Resourceful)
        #   - authorize, against the record as stored (only if the verb assigns attributes and the loaded record is persisted)
        #   - assign_attributes (optional, speficied ResourcefulVerbDsl, by convention, should default to the implementation in Resourceful)
        #     - after_assign_attributes (optional, specified in Resourceful)
        #   - authorize, against the record as modified by the request
        #   - store_data (optional, speficied ResourcefulVerbDsl, by convention, should default to the implementation in Resourceful)
        #   - respond (typically either redirect or render standalone, specified in VerbDsl), which defaults to render_standalone, performing:
        #     - before_render
        #     - render (unless before_render already redirected)
        def dispatch_standalone_access(verb_config, controller, request_context)
          if verb_config.load_data_block
            request_context.evaluate_with_backfire(&verb_config.load_data_block)
            if global_after_load_data_block
              request_context.evaluate_with_backfire(&global_after_load_data_block)
            end
          end

          if verb_config.assign_attributes_block
            # Authorize the record as stored before the request changes it. Otherwise params could alter the very attributes the
            # authorization depends on (e.g. an owner id), and assigning could have side effects for users who may not touch the
            # record at all. New records have no stored state, they are authorized after assignment only.
            authorize_standalone_access!(verb_config, request_context) if @data.respond_to?(:persisted?) && @data.persisted?

            request_context.evaluate_with_backfire(&verb_config.assign_attributes_block)
            if global_after_assign_attributes_block
              request_context.evaluate_with_backfire(&global_after_assign_attributes_block)
            end
          end

          # Authorize the record as the request leaves it, e.g. to check whether the user may access the new owner.
          authorize_standalone_access!(verb_config, request_context)

          if verb_config.store_data_block
            request_context.evaluate_with_backfire(&verb_config.store_data_block)
          end

          # Check if there is a specific respond block for the format.
          # If there isn't, fallback to the nil respond block, which defaults to `render_standalone`.
          respond_block = verb_config.respond_blocks[controller.request.format.symbol] || verb_config.respond_blocks[nil]
          request_context.evaluate(&respond_block)
        end

        # Evaluates the verb's authorize block and raises CanCan::AccessDenied if it is falsy. Do not call directly.
        def authorize_standalone_access!(verb_config, request_context)
          # TODO: Make much prettier, providing message, action, subject and conditions
          fail CanCan::AccessDenied, [inspect, verb_config.authorize_block.inspect].join(', ') unless request_context.evaluate(&verb_config.authorize_block)
        end

        # Call this on a standalone component to find out whether default GET access is permitted for the current user.
        # This is useful to hide/disable buttons leading to components a user may not press.
        # For resourceful components, before calling this, you must have loaded date beforehand, for instance in one of the following ways:
        # - when called standalone (via request to the component), the load data step must be completed
        # - when called to check for permission only, e.g. to display a button to it, initialize the component by passing the :data keyword to `new`
        # By default, this checks the authorization to access the main standalone entrypoint (with name `nil`) and HTTP verb GET.
        def standalone_access_permitted_for?(controller, standalone_name: nil, verb: nil)
          verb ||= :get
          standalone_name = standalone_name&.to_sym
          verb = verb.to_sym
          standalone_config = standalone_configs[standalone_name] || fail("#{inspect} does not provide the standalone config #{standalone_config.inspect}.")
          verb = standalone_config.verbs[verb] || fail("#{inspect} standalone config #{standalone_config.inspect} does not provide verb #{verb.inspect}.")
          return RequestContext.new(self, controller).evaluate(&verb.authorize_block)
        end

        # Renders the component using the controller passed to it upon instanciation (calls the controller's render)
        # Do not overwrite
        def render_standalone(controller, status: nil, standalone_name: nil)
          # Start the render process. This produces a nil value if before_render has already produced a response, e.g. a redirect.
          rendered_html = render(controller, standalone: true)
          if rendered_html.present? # If nil, a response body was already produced in the controller and we take no action here (would have DoubleRenderError)
            opts = { html: rendered_html, layout: @standalone_configs[standalone_name].layout }
            opts[:status] = status if status.present?
            controller.respond_to do |format|
              # Form posts trigger format types turbo stream and then html, turbo stream wins.
              # For this reason, Rails prefers stream, in which case the layout is disabled, regardless of the option.
              # To mitigate this, we use respond_to to force a HTML-only response.
              format.html { controller.render(**opts) }
            end
          end
        end

        protected

        # DSL method
        # This can be called multiple times to make a component listen to multiple paths. Each standalone config (path) has a name, the default being `nil`.
        # To have a component listen to multiple paths, call standalone again and provide a name, e.g.: standalone(:autocomplete, path: 'foo/bar/autocomplete')
        # The kwarg parameter `path` is handled analog to the Rails route path
        # @param name [Symbol,nil] The name of the standalone config, defaults to nil. Only provide if you add additional configs.
        def standalone(name = nil, *, **nargs, &block)
          block = proc {} unless block_given? # If called without a block, must default to an empty block to provide a binding to the DSL.
          name = name&.to_sym # nil name is the most common case
          if @standalone_configs[name]
            @standalone_configs[name].deep_merge! StandaloneDsl.new(self, name, *, provide_defaults: false, **nargs).to_conf(&block)
          else
            @standalone_configs[name] = Compony::MethodAccessibleHash.new(StandaloneDsl.new(self, name, *, provide_defaults: true, **nargs).to_conf(&block))
          end
        end

        # Undoes previous standalone calls
        def clear_standalone!
          @standalone_configs = {}
        end

        # Returns the name of the ComponyController action for this component.<br>
        # Optionally can pass a name for extra standalone configs.
        # @param name [String,Symbol] If referring to an extra standalone entrypoint, specify its name using this param.
        # @see Compony#path
        def rails_action_name(name = nil)
          [name.presence, comp_name, family_name].compact.join('_')
        end

        # Returns the name of the Rails URL helper returning the path to this component.<br>
        # Optionally can pass a name for extra standalone configs.
        # @param name [String,Symbol] If referring to an extra standalone entrypoint, specify its name using this param.
        # @see Compony#path
        def path_helper_name(...)
          "#{rails_action_name(...)}_comp"
        end

        private

        def init_standalone
          @standalone_configs = {}
        end
      end
    end
  end
end
